function cambiaStile() {
    const paragrafo = document.getElementById("paragrafo");

    paragrafo.style.backgroundColor = "red";
    paragrafo.style.fontSize = "25px";
    paragrafo.style.color = "white";
    console.log(paragrafo);
}

